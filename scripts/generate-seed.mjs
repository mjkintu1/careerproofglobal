// Generates supabase/seed.sql from packages/sample-data (single source of truth).
// Usage: npm run db:seed:generate
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { careerSeed, locations } from "./seed-careers.mjs";
import { subjectSeed } from "./seed-subjects.mjs";
import { sourceSeed } from "./seed-sources.mjs";

const dataDir = join(import.meta.dirname, "..", "packages", "sample-data", "src");
const read = (f) => JSON.parse(readFileSync(join(dataDir, f), "utf8"));

const countries = [
  { iso: "UG", name: "Uganda", currency: "UGX", frameworkName: "Uganda Advanced Certificate of Education", rules: read("ug-rules.json"), programmes: read("ug-programmes.json") },
  { iso: "KE", name: "Kenya", currency: "KES", frameworkName: "Kenya Certificate of Secondary Education", rules: read("ke-rules.json"), programmes: read("ke-programmes.json") },
];

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const kindFor = (scale) => (scale === "principal" ? "principal" : scale === "subsidiary" ? "subsidiary" : "general");
const fieldName = (slug) => slug.charAt(0).toUpperCase() + slug.slice(1);

const out = [
  "-- GENERATED by scripts/generate-seed.mjs from packages/sample-data. Do not edit by hand.",
  "-- ILLUSTRATIVE DEMO DATA: rule values are unverified; DEMO-* codes and all cut-offs are made up.",
  "",
];

out.push("insert into public.regions (iso_code, name, currency, secondary_exams, sort_order) values");
out.push(locations.map((l, i) => `  (${q(l.code)}, ${q(l.name)}, ${q(l.currency)}, ${q(l.secondaryExams)}, ${i})`).join(",\n") + ";", "");

const fields = new Set(countries.flatMap((c) => c.programmes.map((p) => p.field)));
out.push("insert into public.fields (slug, name) values");
out.push([...fields].map((f) => `  (${q(f)}, ${q(fieldName(f))})`).join(",\n") + ";", "");

for (const c of countries) {
  const fw = c.rules.framework;
  const fwId = `(select id from public.education_frameworks where code = ${q(fw)})`;
  const rsId = `(select id from public.rule_sets where framework_id = ${fwId} and version = ${q(c.rules.version)})`;
  out.push(`-- ${c.name}`);
  out.push(`insert into public.education_frameworks (region_id, code, name, level) values ((select id from public.regions where iso_code = ${q(c.iso)}), ${q(fw)}, ${q(c.frameworkName)}, 'upper_secondary');`);
  out.push(`insert into public.rule_sets (framework_id, version, rules, status) values (${fwId}, ${q(c.rules.version)}, ${q(JSON.stringify(c.rules))}::jsonb, 'illustrative');`);
  out.push("insert into public.subjects (framework_id, code, name, kind) values");
  out.push(Object.entries(c.rules.subjects).map(([code, s]) => `  (${fwId}, ${q(code)}, ${q(s.name)}, ${q(kindFor(s.scale))})`).join(",\n") + ";");

  const institutions = new Map(c.programmes.map((p) => [p.institution, p.institutionType]));
  out.push("insert into public.institutions (region_id, name, type) values");
  out.push([...institutions].map(([name, type]) => `  ((select id from public.regions where iso_code = ${q(c.iso)}), ${q(name)}, ${q(type)})`).join(",\n") + ";");

  for (const p of c.programmes) {
    const fieldId = `(select id from public.fields where slug = ${q(p.field)})`;
    const instId = `(select id from public.institutions where name = ${q(p.institution)})`;
    out.push(`insert into public.degrees (field_id, name, level) values (${fieldId}, ${q(p.title)}, 'bachelor') on conflict (name, level) do nothing;`);
    out.push(`insert into public.programmes (institution_id, degree_id, national_code, title) values (${instId}, (select id from public.degrees where name = ${q(p.title)} and level = 'bachelor'), ${q(p.code)}, ${q(p.title)});`);
    const progId = `(select id from public.programmes where national_code = ${q(p.code)})`;
    const subjId = (code) => `(select id from public.subjects where framework_id = ${fwId} and code = ${q(code)})`;
    const reqs = [];
    for (const role of ["essential", "relevant", "desirable", "cluster"]) {
      for (const code of p.requirements[role] ?? []) reqs.push(`  (${progId}, ${rsId}, ${subjId(code)}, ${q(role)}, null)`);
    }
    for (const m of p.requirements.mandatory ?? []) reqs.push(`  (${progId}, ${rsId}, ${subjId(m.subject)}, 'mandatory', ${q(m.minGrade)})`);
    if (reqs.length) out.push("insert into public.programme_requirements (programme_id, rule_set_id, subject_id, role, min_grade) values", reqs.join(",\n") + ";");
    out.push("insert into public.historical_cutoffs (programme_id, intake_year, points, is_illustrative) values");
    out.push(p.cutoffs.map((k) => `  (${progId}, ${k.year}, ${k.points}, true)`).join(",\n") + ";");
  }
  out.push("");
}

out.push(...careerSeed(q), "");
out.push(...subjectSeed(q), "");
out.push(...sourceSeed(q), "");

const target = join(import.meta.dirname, "..", "supabase", "seed.sql");
writeFileSync(target, out.join("\n") + "\n");
console.log(`Wrote ${target}`);
